import { readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { glob } from 'glob';
import sharp from 'sharp';
import { loadMagnetCatalogue } from '../src/data/magnet-covers.ts';

const root = fileURLToPath(new URL('../', import.meta.url));
const assetDir = join(root, 'src/assets/magnet-covers');
const files = await glob('src/data/magnet-covers/*.yaml', { cwd: root });
const documents = await Promise.all(files.sort().map(async file => [file, await readFile(join(root, file), 'utf8')]));
const assets = await glob('**/*.webp', { cwd: assetDir });
const reviewFiles = await glob('content/reviews/*/index.md', { cwd: root });
const covers = loadMagnetCatalogue(Object.fromEntries(documents), new Set(assets), new Set(reviewFiles.map(f => basename(dirname(f)))));
const bySeries = Map.groupBy(covers, cover => cover.series.name);
const lines = [
  '# Book magnet cover inventory', '',
  '<!-- Generated by npm run inventory:covers from src/data/magnet-covers/*.yaml and the actual WebP assets. -->', '',
  `The [workshop](https://cosmiccoding.com.au/reviews/book-magnets/) includes ${covers.length} curated covers across ${bySeries.size} series and standalone works. Individual review covers also appear in the workshop.`, '',
  '[Catalogue editing and source notes](book-magnet-cover-notes.md)', '',
];

const cell = (value: string) => value.replaceAll('|', '\\|').replace(/\s*\n\s*/g, ' ');
for (const name of [...bySeries.keys()].sort((a, b) => a.localeCompare(b, 'en'))) {
  const editions = Map.groupBy(bySeries.get(name)!, cover => cover.editionId);
  lines.push('## ' + name, '');
  for (const books of editions.values()) {
    const first = books[0];
    if (first.series.edition) lines.push('### ' + first.series.edition, '');
    if (first.notes) lines.push(first.notes, '');
    lines.push('| Volume | Title | Author | WebP | Sources |', '| --- | --- | --- | --- | --- |');
    for (const book of books) {
      const { width, height, format } = await sharp(join(assetDir, book.cover)).metadata();
      if (format !== 'webp') throw new Error('Expected a WebP image: ' + book.cover);
      const { volume, part, collection, omnibus } = book.series;
      const number = collection ? 'Collection' : omnibus ? 'Omnibus ' + volume : String(volume);
      const position = part ? number + ', part ' + part : number;
      const links = book.sources.map(([label, url]) => `[${cell(label)}](<${url}>)`);
      lines.push(`| ${position} | ${cell(book.title)} | ${cell(book.author)} | [${width} × ${height}](../src/assets/magnet-covers/${book.cover}) | ${links.join(' · ')} |`);
    }
    lines.push('');
  }
}

await writeFile(join(root, 'docs/book-magnet-cover-inventory.md'), lines.join('\n'));
console.log(`Generated inventory for ${covers.length} covers across ${bySeries.size} series and standalone works.`);
